void drawMap(void)
{
    for (int i = 0; i < 24; i++)
    {
        for (int j = 0; j < 32; j++)
        {
            if (map[i][j] == 'W')
            {
                int x = j * 25;
                int y = i * 25;
                drawRectARGB32(x, y, x + 25, y + 25, 0x000000CC, 2);
            }
        }
    }
    drawString(20, 560, "WASD: Move  |  B: Back  |  Q: Main Menu", 0xFFFFFF, 2);
}